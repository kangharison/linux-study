/*
 * [한국어 설명] Freescale PAMU 도메인 자료 구조 헤더 (fsl_pamu_domain.h)
 *
 * === 파일의 역할 ===
 * PowerPC 계열 Freescale(현 NXP) SoC 에 들어가는 PAMU(Peripheral Access
 * Management Unit)의 도메인 자료 구조를 정의한다. 구조체 둘이 전부인
 * 아주 짧은 헤더다.
 * PAMU 는 다른 IOMMU 와 성격이 꽤 다르다. 임의의 페이지 테이블을 걸어
 * 주소를 번역하는 것이 아니라, 장치(LIODN 으로 식별)마다 접근할 수 있는
 * 메모리 창과 캐시 스태시 대상을 정해 주는 방식이다. 그래서 도메인
 * 구조체에도 페이지 테이블이 없고 스태시 대상 번호만 들어 있다.
 * 지금은 통과(identity) 도메인만 지원하는 축소된 상태로 남아 있다 —
 * 창 기반 매핑을 iommu 코어의 모델에 맞추기 어려워 그 기능이 걷혔다.
 *
 * === 전체 아키텍처에서의 위치 ===
 * iommu 코어 → fsl_pamu_domain.c 의 연산표 → 여기 정의된 구조체 →
 * fsl_pamu.c 가 PAMU 하드웨어 표(PAACT)를 고친다.
 * 장치 하나는 LIODN 이라는 번호로 식별되고, 그 번호가 하드웨어 표의
 * 첨자가 된다. 도메인에 장치를 붙인다는 것은 곧 그 번호의 표 항목을
 * 도메인의 설정으로 채우는 일이다.
 *
 * === 타 모듈과의 연결 ===
 * - fsl_pamu.h: 하드웨어 표의 구조와 조작 함수를 제공한다.
 * - fsl_pamu_domain.c: 여기 정의된 구조체를 실제로 다루는 연산표 구현.
 * - iommu 코어: iommu_domain 을 통해 이 도메인과 만난다 — 그래서
 *   struct fsl_dma_domain 이 그것을 품고 있다.
 *
 * === 주요 함수/구조체 요약 ===
 * - struct fsl_dma_domain: 주소 공간 하나. 붙어 있는 장치 목록과 스태시
 *   대상 번호를 쥔다.
 * - struct device_domain_info: 도메인과 장치를 잇는 고리. 장치의 LIODN 이
 *   여기 담겨, 하드웨어 표의 어느 항목을 고칠지 알려 준다.
 */

#ifndef __FSL_PAMU_DOMAIN_H	/* [한국어] 이 헤더가 두 번 펼쳐지는 것을 막는 보호 매크로. */
#define __FSL_PAMU_DOMAIN_H	/* [한국어] 처음 펼쳐질 때 표시를 남긴다. */

#include "fsl_pamu.h"	/* [한국어] 하드웨어 표의 구조와 조작 함수 — 이 헤더의 구조체가 그것과 짝을 이룬다. */

/* [한국어] PAMU 의 주소 공간 하나.
 *
 * 페이지 테이블이 없다는 점이 다른 IOMMU 와 가장 크게 다르다. PAMU 는
 * 장치마다 접근 가능한 메모리 창을 정해 주는 방식이라, 도메인이 들고 있을
 * 것이 스태시 설정과 붙어 있는 장치 목록뿐이다. */
struct fsl_dma_domain {
	/* list of devices associated with the domain */
	/* [한국어] (위 영어 주석 참고) 이 도메인에 붙어 있는 장치들의 고리 목록.
	 * 설정자: 장치를 붙일 때 device_domain_info 를 만들어 여기 단다.
	 * 읽는 자: 도메인 설정이 바뀌면 이 목록을 훑어 각 장치의 하드웨어 항목을
	 *         모두 고쳐야 한다.
	 * 값 범위: 비어 있을 수 있다 — 아직 아무도 붙지 않은 도메인이다.
	 * 동기화: 아래 domain_lock 아래에서만 다룬다. */
	struct list_head		devices;
	/* [한국어] 캐시 스태시 대상 번호 — DMA 로 들어온 데이터를 어느 CPU 캐시에
	 * 미리 넣어 둘지 정한다.
	 * 설정자: 장치를 붙일 때 그 장치와 가까운 CPU 를 골라 정한다.
	 * 읽는 자: 하드웨어 표 항목을 채울 때.
	 * 값 범위: 하드웨어가 정의한 스태시 대상 번호. 쓰지 않으면 무효 값이다.
	 * 동기화: 도메인 설정의 일부라 domain_lock 아래에서 다룬다.
	 *         (PAMU 만의 기능으로, 네트워크처럼 지연이 중요한 부하에서
	 *          DMA 직후의 CPU 접근을 빠르게 만든다.) */
	u32				stash_id;
	/* [한국어] iommu 코어가 아는 도메인 몸통.
	 * 설정자: 도메인을 만들 때 코어의 규칙에 따라 채운다.
	 * 읽는 자: container_of 로 이 구조를 되찾는 모든 곳, 그리고 코어 자신.
	 * 값 범위: 지금은 통과 도메인만 지원한다.
	 * 동기화: 코어의 도메인 수명 규칙을 따른다. */
	struct iommu_domain		iommu_domain;
	/* [한국어] 위 목록과 스태시 설정을 지키는 락.
	 * 설정자: 도메인을 만들 때 초기화한다.
	 * 읽는 자: 장치를 붙이고 떼는 두 경로.
	 * 값 범위: 스핀락 — 짧은 구간만 감싼다.
	 * 동기화: 이 필드 자체가 동기화 장치다. */
	spinlock_t			domain_lock;
};

/* domain-device relationship */
/* [한국어] (위 영어 주석 참고) 도메인과 장치를 잇는 고리 하나.
 *
 * 장치 하나가 도메인 하나에만 붙으므로 고리도 하나뿐이지만, 도메인 쪽에서
 * 붙어 있는 장치를 모두 훑을 수 있어야 해서 이런 구조를 둔다. */
struct device_domain_info {
	struct list_head link;	/* link to domain siblings */
	/* [한국어] (위 영어 주석 참고) 같은 도메인에 붙은 다른 장치들과 잇는 고리.
	 * 설정자: 장치를 붙일 때 도메인의 devices 목록에 단다.
	 * 읽는 자: 도메인 설정을 모든 장치에 반영할 때.
	 * 값 범위: 목록에서 빠지면 초기화된 상태로 둔다.
	 * 동기화: 도메인의 domain_lock 아래. */
	/* [한국어] 이 고리가 가리키는 장치.
	 * 설정자: 붙일 때 채운다.
	 * 읽는 자: 로그를 찍거나 장치별 정보를 꺼낼 때.
	 * 값 범위: NULL 일 수 없다.
	 * 동기화: 고리가 사는 동안 바뀌지 않는다. */
	struct device *dev;
	/* [한국어] 그 장치의 LIODN — PAMU 가 장치를 식별하는 번호.
	 * 설정자: 펌웨어(장치 트리)가 알려 준 값을 붙일 때 옮겨 담는다.
	 * 읽는 자: 하드웨어 표에서 어느 항목을 고칠지 정할 때 — 이 번호가
	 *         곧 표의 첨자다.
	 * 값 범위: 하드웨어가 지원하는 LIODN 범위 안.
	 * 동기화: 고리가 사는 동안 바뀌지 않는다. */
	u32 liodn;
	struct fsl_dma_domain *domain; /* pointer to domain */
	/* [한국어] (위 영어 주석 참고) 이 장치가 붙어 있는 도메인.
	 * 설정자: 붙일 때 채운다.
	 * 읽는 자: 장치에서 도메인 설정을 되짚어 갈 때.
	 * 값 범위: NULL 이면 아직 어디에도 붙지 않았다.
	 * 동기화: 도메인의 domain_lock 아래. */
};
#endif  /* __FSL_PAMU_DOMAIN_H */

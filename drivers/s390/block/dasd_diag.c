/* [한국어] [한국어 설명] z/VM DIAG 250 디시플린 본체 (dasd_diag.c)
 * 
 * === 파일의 역할 ===
 * DASD 드라이버는 장치 종류마다 디시플린(discipline)이라는 가상 함수표를 갈아
 * 끼우는 구조인데, 이 파일은 그중 **DIAG 판** 전체다. 같은 디렉터리의 ECKD·FBA
 * 디시플린이 struct ccw1 을 이어 붙인 채널 프로그램을 만들어 채널 서브시스템에
 * 내보내는 것과 달리, 이 파일은 **채널 프로그램을 아예 만들지 않는다.**
 * 대신 dasd_diag.h 의 파라미터 블록을 채우고 DIAG 명령 한 번을 실행해,
 * z/VM 하이퍼바이저에게 '이 블록들을 읽어/써 달라' 고 부탁한다. 게스트가 직접
 * 장치를 몰지 않고 하이퍼바이저에게 대신 시키는 것 — 그것이 이 파일의 전부다.
 * 
 * 파일 하나가 곧 하나의 커널 모듈이다(Makefile 의 dasd_diag_mod 는 이 파일의
 * 오브젝트 하나로만 이루어진다). 안에 든 것은 크게 넷이다.
 *  (1) DIAG 명령을 감싼 인라인 함수 둘 — 인라인 어셈블리가 있는 유일한 자리다.
 *  (2) 그 위에 얹은 얇은 도우미 셋 — 세션 열기, 세션 닫기, 오류 복구.
 *  (3) 디시플린 vtable 이 요구하는 콜백 열셋.
 *  (4) 완료를 받는 **외부 인터럽트 처리기** 하나와 모듈 등록·해제 함수 둘.
 * 
 * 읽을 때 붙들고 있어야 할 물음은 하나다 — **'채널이 하던 일을 누가 대신 하고,
 * 그래서 무엇이 사라졌는가.'** 익스텐트 정의도, 레코드 위치 지정도, 센스 데이터도,
 * 간접 주소 목록도 여기에는 없다. 남은 것은 블록 번호와 버퍼 주소의 배열뿐이다.
 * 
 * === 전체 아키텍처에서의 위치 ===
 * 이 디시플린이 쓰이는 조건은 둘이다. 리눅스가 z/VM 게스트로 돌아야 하고
 * (모듈 초기화가 그것을 먼저 확인한다), 장치에 use_diag 기능이 켜져 있어야 한다
 * (커널 파라미터의 'diag' 나 sysfs 속성 use_diag 로 켠다 — dasd_devmap.c:197 과
 * dasd_devmap.c:1102 의 상류 주석 참고).
 * 
 * 블록 요청 하나가 하이퍼바이저에 닿기까지의 길은 이렇다.
 * 
 *   파일시스템 / 사용자 공간
 *     -> blk-mq -> dasd.c:3018 의 do_dasd_request()   [프로세스·softirq 문맥]
 *       -> discipline->build_cp (dasd.c:3067) == 이 파일의 dasd_diag_build_cp()
 *          [struct dasd_diag_bio 배열을 블록 개수만큼 채운다]
 *         -> block->ccw_queue 에 매달린다             [블록 계층 큐]
 *           -> dasd_block_tasklet 이 device->ccw_queue 로 옮긴다  [softirq]
 *             -> dasd.c:2018 의 discipline->start_IO == 이 파일의 dasd_start_diag()
 *                [struct dasd_diag_rw_io 를 채우고 DIAG 명령을 실행]  [cdev 락 보유]
 *               -> z/VM 이 실제 I/O 를 수행
 * 
 * 완료는 두 갈래로 돌아온다. **여기가 이 파일에서 가장 중요한 대목** 이다.
 * 
 *  (가) 동기 완료 — DIAG 호출이 조건 코드 0 으로 돌아오면 I/O 가 이미 끝난 것이다.
 *       dasd_start_diag() 가 그 자리에서 요청을 성공으로 표시하고, 호출자에게는
 *       -EACCES 를 돌려준다. dasd.c:2021 이 그 값을 특별히 알아보고 타이머를 걸지
 *       않은 채 tasklet 만 깨운다.
 *  (나) 비동기 완료 — 조건 코드 8 이면 시작만 된 것이다. 나중에 **외부 인터럽트**
 *       로 완료가 온다.
 * 
 *       z/VM -> 외부 인터럽트 (서비스 신호)
 *         -> 이 파일의 dasd_ext_handler()          [인터럽트 문맥]
 *           -> 부코드 상위 바이트로 인자의 폭을 가려 요청 주소를 얻는다
 *             -> 매직 값 대조로 남의 인터럽트를 거른다
 *               -> cdev 락을 잡고 cqr->status 갱신
 *                 -> 큐의 다음 요청을 곧바로 시작(fast_io)
 *                   -> dasd_schedule_device_bh() 로 tasklet 을 깨운다
 * 
 * **채널 인터럽트가 아니라 외부 인터럽트라는 점** 이 이 디시플린을 특별하게 만든다.
 * 채널 인터럽트는 장치별로 오지만 외부 인터럽트는 시스템 전체에 하나의 처리기로
 * 온다. 그래서 dasd.c:1633 은 DIAG 디시플린인 장치의 요청 없는 채널 인터럽트를
 * 아예 무시하도록 예외를 두고 있고, 이 파일의 처리기는 인터럽트 인자로 받은
 * 주소를 믿기 전에 매직 값을 반드시 대조한다.
 * 
 * === 타 모듈과의 연결 ===
 * **dasd.c 와의 연결이 전역 포인터 하나로만 이루어진다는 점이 이 파일의 특징이다.**
 * dasd_int.h 가 디시플린 중 유일하게 전역으로 노출한 것이 DIAG 라고 적어 둔 그
 * 포인터이며, 이유는 모듈 구조에 있다. ECKD·FBA 는 장치를 인식하는 쪽에서
 * '등록된 디시플린 목록' 을 뒤져 찾지만, DIAG 는 **장치 종류가 아니라 사용자
 * 설정으로 고르는** 디시플린이다. 코어 모듈이 use_diag 를 보고 DIAG 를 써야 한다고
 * 판단했을 때, 그 모듈이 아직 메모리에 없을 수도 있다. 그래서 코어는
 *  - dasd.c:46 에 빈 포인터를 두고 dasd.c:47 에서 그것을 내보내고,
 *  - dasd.c:4050 에서 초기화 때 NULL 로 비우고,
 *  - dasd.c:3469 에서 그것이 비어 있으면 dasd.c:3471 로 모듈을 적재 요청하고,
 *  - dasd.c:3483 에서 다시 확인한 뒤 dasd.c:3488 에서 그것을 디시플린으로 삼는다.
 * 이 파일은 반대편에서 그 칸에 자기 vtable 주소를 써 넣고(모듈 초기화), 내릴 때
 * 다시 NULL 로 지운다(모듈 정리). 즉 **적재 순서를 뒤집을 수 있게 하려고 함수
 * 호출 대신 변수 하나를 약속으로 삼은** 구조다.
 * 
 * 그 밖의 연결은 이렇다.
 *  - dasd_diag.h: 이 파일만이 포함하는 전용 헤더. 파라미터 블록 구조체 셋과
 *    블록 서술자, 기능 코드, 플래그 비트가 거기 있다.
 *  - dasd_int.h: struct dasd_device / dasd_block / dasd_ccw_req, 디시플린 vtable,
 *    요청 상태 상수, 정적 메모리 풀 할당기, DASD_DIAG_MAGIC(dasd_int.h:266).
 *  - dasd.c: 요청 할당·해제(dasd_smalloc_request / dasd_sfree_request),
 *    블록 구조체 할당·해제, tasklet 예약, 장치 타이머, 경로 확인 기본 구현.
 *  - dasd_erp.c: 이 디시플린은 자기 오류 복구를 만들지 않고 기본 구현 둘을
 *    그대로 되돌려 준다(dasd_erp.c:450 과 dasd_erp.c:569).
 *  - dasd_ioctl.c:513: 사용자 공간의 장치 정보 조회가 이 파일의 채우기 콜백에 닿는다.
 *  - dasd_genhd.c:431: 블록 계층 태그셋의 명령 크기가 struct dasd_ccw_req 크기로
 *    잡혀 있어, 요청마다 cqr 이 하나씩 딸려 온다. 이 파일의 요청 생성 콜백은
 *    그 자리를 그대로 쓴다.
 * 
 * 아래로는 s390 아키텍처 계층에 기대는데 **이 트리는 sparse checkout 이라
 * arch/s390 이 통째로 없다.** DIAG 명령의 의미와 조건 코드 규약, 진단 호출로
 * 장치 특성을 읽는 절차, struct ext_code 의 부코드 배치, 외부 인터럽트 등록,
 * EBCDIC 변환, TOD 시계 읽기, z/VM 게스트 여부 판정이 모두 그 계층 소관이라
 * 이 트리에서 확인 못 함이다. 이 파일의 주석은 그 계층의 규약을 단정하지 않고,
 * **이 코드가 그것을 어떻게 쓰는지** 만 적는다.
 * 
 * 데이터 흐름을 한 줄로 요약하면 이렇다. 블록 계층의 struct request 가
 * dasd_diag_build_cp() 에서 struct dasd_diag_bio 배열로 바뀌고, 그 배열의 주소가
 * dasd_start_diag() 에서 struct dasd_diag_rw_io 에 담겨 z/VM 으로 간다. 돌아오는
 * 길에는 요청의 주소가 인터럽트 인자로 실려 와 dasd_ext_handler() 가 그것으로
 * 원래 요청을 되찾는다.
 * 
 * === 주요 함수/구조체 요약 ===
 * __dia250()                 DIAG 명령을 실행하는 인라인 어셈블리. 이 파일에서
 *                            하드웨어(정확히는 하이퍼바이저)에 직접 닿는 유일한 곳.
 * dia250()                   위의 얇은 껍데기. 진단 호출 통계를 하나 올리고 부른다.
 * mdsk_init_io()             블록 I/O 세션을 연다. 블록 크기와 오프셋을 건네고
 *                            마지막 블록 번호를 받아 온다.
 * mdsk_term_io()             블록 I/O 세션을 닫는다.
 * dasd_diag_erp()            DIAG 판의 오류 복구 — 세션을 닫았다 다시 연다.
 *                            읽기 전용으로 바뀐 경우를 여기서 알아챈다.
 * dasd_start_diag()          디시플린의 start_IO 콜백. 요청 하나를 DIAG 로 내보내고
 *                            동기 완료와 비동기 시작을 갈라 처리한다.
 * dasd_diag_term_IO()        디시플린의 term_IO 콜백. 세션을 닫았다 다시 여는 것으로
 *                            진행 중인 I/O 를 지운다.
 * dasd_ext_handler()         완료 외부 인터럽트 처리기. 이 파일에서 유일하게
 *                            인터럽트 문맥에서 도는 함수다.
 * dasd_diag_check_device()   장치 인식. 특성을 읽고, 블록 크기를 512 부터 시험으로
 *                            알아내고, CMS 레이블을 읽어 볼륨 크기를 정한다.
 *                            이 파일에서 가장 긴 함수다.
 * dasd_diag_build_cp()       디시플린의 build_cp 콜백. 블록 계층 요청을
 *                            struct dasd_diag_bio 배열로 옮긴다.
 * dasd_diag_free_cp()        요청을 풀고 성공 여부를 상위에 알린다.
 * dasd_diag_discipline       이 파일이 채우는 vtable. 콜백 열셋만 채우고 나머지는
 *                            비워 둔다 — DIAG 에는 없는 기능이 그만큼 많다는 뜻이다.
 * struct dasd_diag_private   장치마다 하나. 장치 특성, 읽기·쓰기 파라미터 블록,
 *                            초기화 파라미터 블록, 레이블 블록 위치, 장치 식별자.
 * struct dasd_diag_req       요청마다 하나. 블록 개수와 가변 길이 서술자 배열.
 * 
 * === DIAG 경로가 CCW 채널 프로그램과 무엇이 다른가 ===
 * 같은 디렉터리의 ECKD·FBA 와 이 파일을 나란히 놓으면 차이가 여섯 군데다.
 * 
 *  (1) **만드는 것.** ECKD·FBA 는 struct ccw1 사슬을 만들어 cqr->cpaddr 에 매단다.
 *      이 파일은 요청을 할당할 때 CCW 개수 자리에 0 을 넘기므로(dasd_diag_build_cp
 *      안의 할당 호출), dasd.c:1162 의 조건이 거짓이 되어 **cpaddr 이 끝까지
 *      NULL 로 남는다.** 그 자리를 struct dasd_diag_bio 배열이 대신한다.
 * 
 *  (2) **시작하는 방법.** 채널 시작 명령 대신 DIAG 명령 한 번이다. 게다가 그
 *      한 번이 동기 완료로 끝날 수 있어, start_IO 콜백이 '이미 끝났다' 는 뜻으로
 *      -EACCES 를 돌려주는 특이한 규약이 생겼다.
 * 
 *  (3) **완료를 받는 방법.** I/O 인터럽트와 struct irb 대신 외부 인터럽트와
 *      부코드 한 워드다. 그래서 이 파일의 센스 덤프 콜백은 '해 줄 말이 없다' 는
 *      메시지만 남긴다.
 * 
 *  (4) **오류 복구.** ECKD 는 제어 장치의 센스 바이트를 해석하는 거대한 상태
 *      기계를 갖지만, 여기에는 해석할 센스가 없다. 복구란 곧 세션을 다시 여는
 *      것이며, 그 김에 미니디스크가 읽기 전용으로 바뀌었는지를 알아챈다.
 * 
 *  (5) **요청 취소.** 개별 요청만 지우는 수단이 없어, 세션 전체를 닫았다 연다.
 *      그래서 term_IO 콜백은 같은 장치의 다른 요청까지 함께 끊는 셈이 된다.
 * 
 *  (6) **경로 관리.** 채널 경로가 여럿이라는 개념이 DIAG 에는 없다. 그래서 경로
 *      확인 콜백은 코어의 기본 구현(dasd.c:3797)을 그대로 부르고, 보안 채널
 *      경로 인자는 쓰지 않는다.
 * 
 * === DIAG 호출의 반환값 규약 — 이 파일을 읽기 전에 알아 둘 것 ===
 * 이 파일의 함수 대부분이 int 를 돌려주는데, 그 값이 **두 가지 다른 체계** 로
 * 섞여 있어 헷갈리기 쉽다.
 * 
 *  - dia250() 과 그것을 감싼 mdsk_init_io() / mdsk_term_io() 는 **DIAG 쪽 값** 을
 *    그대로 돌려준다. 상류 주석이 밝히듯 '조건 코드와 DIAG 반환 코드의 비트 OR' 이며,
 *    예외가 나면 3 이다. 이 파일이 실제로 구분해 쓰는 값은 넷이다 —
 *    0(성공 또는 동기 완료), 3(예외 — 64비트 DIAG 호출 실패),
 *    4(성공했으나 읽기 전용), 8(비동기로 시작됨).
 *  - 디시플린 콜백들은 **리눅스 오류 코드** 를 돌려준다. 0, -EIO, -ENOMEM,
 *    -EOPNOTSUPP, -EINVAL, 그리고 앞서 말한 특이한 -EACCES 다.
 * 
 * 두 체계가 만나는 자리가 dasd_start_diag() 의 분기문과 dasd_diag_check_device()
 * 의 반환값 변환이다. 그 두 곳에서 DIAG 값이 리눅스 값으로 번역된다.
 * 조건 코드와 DIAG 반환 코드가 하이퍼바이저 쪽에서 각각 무엇을 뜻하는지는
 * z/VM 인터페이스 문서 소관이라 이 트리에서 확인 못 함이며, 여기서는 이 코드가
 * 그 값들을 어떻게 나누어 쓰는지만 적는다. */
